export type Theme = {colors: Record<string,string>; gradients: Record<string,{start:string;middle:string;end:string;angle:number}>};
export const defaultTheme:Theme={colors:colorDefaults,gradients:gradientDefaults};
export const validHex=(v:unknown):v is string=>typeof v==='string'&&/^#[0-9a-f]{6}$/i.test(v);
export function normalizeTheme(value:any):Theme {
 const colors={...colorDefaults}; for(const k of Object.keys(colors))if(validHex(value?.colors?.[k]))colors[k]=value.colors[k];
 const gradients={};for(const [k,d] of Object.entries(gradientDefaults)){const g=value?.gradients?.[k];gradients[k]={...d};for(const stop of ['start','middle','end'])if(validHex(g?.[stop]))gradients[k][stop]=g[stop];if(typeof g?.angle==='number'&&Number.isFinite(g.angle))gradients[k].angle=Math.max(0,Math.min(360,g.angle));}
 return {colors,gradients};
}
export function themeVariables(value:any):Record<string,string>{const t=normalizeTheme(value),css={};for(const[k,v]of Object.entries(t.colors))css['--seacom-'+k]=[1,3,5].map(i=>parseInt(v.slice(i,i+2),16)).join(' ');for(const[k,g]of Object.entries(t.gradients))css['--seacom-gradient-'+k]='linear-gradient('+g.angle+'deg, '+g.start+', '+g.middle+', '+g.end+')';return css;}
export function contrast(a:string,b:string){const lum=(h:string)=>{const c=[1,3,5].map(i=>parseInt(h.slice(i,i+2),16)/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4);return c[0]*.2126+c[1]*.7152+c[2]*.0722};const x=lum(a),y=lum(b);return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);}
